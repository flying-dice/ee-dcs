/** Options controlling .miz assembly. */
export interface BuildMizOptions {
  /** Embed the EECH campaign bundle + wire it to run at mission start. Default true —
   *  the output is a directly-playable campaign. Set false for a zones-only .miz. */
  bakeCampaign?: boolean;
  /** Per-side aircraft type overrides. When any differ from the port defaults, a
   *  `_G.DMT_CONFIG` snippet is prepended to the baked bundle. Also drives which aircraft
   *  types get baked Client slots. */
  unitTypes?: UnitTypes;
  /** Bake 4 human-flyable Client slots per aircraft type at each compatible airbase
   *  (needs terrain parking data — see slots.ts). Default true. */
  bakeSlots?: boolean;
  /** Operational framework retained in the archive for campaign coordination tooling. */
  controlMeasures?: ScenarioControlMeasures;
}

/** Deterministic .miz filename for a terrain, e.g. `eech-caucasus.miz`. */
export function filenameFor(terrain: Terrain): string {
  return `eech-${terrain.id.toLowerCase()}.miz`;
}

/**
 * Build a complete, ME-openable .miz (ZIP) for the given keysites and terrain. The
 * archive holds the entries a real .miz needs: `mission`, `options`, `warehouses`,
 * `theatre`, and the DEFAULT localization pair. When `bakeCampaign` is true (default)
 * the campaign bundle is embedded as `l10n/DEFAULT/ee-dcs.lua` and wired
 * to run at mission start, so the file plays the EECH campaign with no further setup.
 * Returns a Blob.
 */
export async function buildMiz(
  keysites: Keysite[],
  terrain: Terrain,
  opts: BuildMizOptions = {},
): Promise<Blob> {
  const bakeCampaign = opts.bakeCampaign ?? true;
  const bakeSlots = opts.bakeSlots ?? true;
  const { default: JSZip } = await import('jszip');

  const zones = keysitesToZones(keysites, terrain);
  const initScriptFile = bakeCampaign ? INIT_SCRIPT_RESKEY : '';
  const slots = bakeSlots ? buildClientSlots(keysites, terrain, opts.unitTypes) : undefined;
  if (slots) {
    console.info(`miz: baked ${slots.slotCount} Client slot(s)`);
    if (slots.notes.length) console.info('miz slot notes:\n  ' + slots.notes.join('\n  '));
  }
  const farps = buildFarps(zones, slots);
  const mission = buildMissionTable(zones, terrain, initScriptFile, slots, farps);
  const missionLua = serializeNamed('mission', mission);

  const zip = new JSZip();
  zip.file('mission', missionLua);
  zip.file('options', OPTIONS_LUA);
  zip.file('warehouses', warehousesLua(farps));
  zip.file('theatre', terrain.id);
  zip.file('l10n/DEFAULT/dictionary', DICTIONARY_LUA);
  zip.file('l10n/DEFAULT/mapResource', bakeCampaign ? MAP_RESOURCE_WITH_INIT : MAP_RESOURCE_EMPTY);
  if (opts.controlMeasures) {
    zip.file(
      'control-measures.geojson',
      JSON.stringify({
        type: 'FeatureCollection',
        properties: { terrain: terrain.id },
        features: controlMeasureGeoJsonFeatures(opts.controlMeasures),
      }, null, 2),
    );
  }
  if (bakeCampaign) {
    // Prepend any aircraft-type overrides so config.lua reads _G.DMT_CONFIG at load,
    // then the campaign bundle itself.
    const cfg = opts.unitTypes ? unitConfigLua(opts.unitTypes) : '';
    zip.file(`l10n/DEFAULT/${CAMPAIGN_LUA_NAME}`, cfg + (await loadCampaignBundle()));
  }

  return zip.generateAsync({
    type: 'blob',
    mimeType: 'application/octet-stream',
    compression: 'DEFLATE',
  });
}
