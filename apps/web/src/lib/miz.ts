// ── Lua table serializer (DCS Mission Editor style) ─────────────────────────────
//
// Emits tab-indented `["key"] = value,` / `[n] = value,` lines exactly the way DCS
// writes mission files. Only needs to serialize the plain JSON-like tables we build
// below (numbers, strings, booleans, nested objects, and arrays).

export type LuaValue = number | string | boolean | LuaTable;
export interface LuaObject {
  [key: string]: LuaValue;
}
export type LuaTable = LuaObject | LuaValue[];

const TAB = '\t';

function indent(level: number): string {
  return TAB.repeat(level);
}

function luaString(s: string): string {
  // Escape backslashes and double quotes; DCS mission strings are double-quoted.
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

function luaNumber(n: number): string {
  if (!Number.isFinite(n)) {
    throw new Error(`miz: refusing to serialize non-finite number (${n})`);
  }
  // Integers print without a decimal point; other values keep full JS precision.
  // Our coordinate/radius ranges never reach exponent notation.
  return String(n);
}

function isTable(v: LuaValue): v is LuaTable {
  return typeof v === 'object' && v !== null;
}

function isEmptyTable(v: LuaTable): boolean {
  return Array.isArray(v) ? v.length === 0 : Object.keys(v).length === 0;
}

/** Serialize a scalar or a table. Tables begin with `{` at column `level`. */
function serializeValue(v: LuaValue, level: number): string {
  switch (typeof v) {
    case 'number':
      return luaNumber(v);
    case 'string':
      return luaString(v);
    case 'boolean':
      return v ? 'true' : 'false';
    default:
      return serializeTable(v as LuaTable, level);
  }
}

function serializeTable(tbl: LuaTable, level: number): string {
  if (isEmptyTable(tbl)) return '{}';

  const pad = indent(level);
  const padIn = indent(level + 1);
  const entries: Array<[string, LuaValue]> = Array.isArray(tbl)
    ? tbl.map((val, i): [string, LuaValue] => [`[${i + 1}]`, val])
    : Object.entries(tbl);

  let out = '{\n';
  for (const [rawKey, val] of entries) {
    const key = rawKey.startsWith('[') ? rawKey : `[${luaString(rawKey)}]`;
    if (isTable(val) && !isEmptyTable(val)) {
      // Nested non-empty table: key on its own line, `{` on the next (DCS style).
      out += `${padIn}${key} = \n${padIn}${serializeValue(val, level + 1)},\n`;
    } else {
      out += `${padIn}${key} = ${serializeValue(val, level + 1)},\n`;
    }
  }
  out += `${pad}}`;
  return out;
}

/** Serialize a named top-level table, e.g. `mission = { … }`, as a .miz entry body. */
export function serializeNamed(name: string, tbl: LuaTable): string {
  return `${name} = \n${serializeTable(tbl, 0)} -- end of ${name}\n`;
}

// ── Keysites → trigger zones ─────────────────────────────────────────────────────

// DCS Mission Editor default trigger-zone fill alpha (38/255). Only R and B are read
// by the port (zones.lua side_of_color); alpha is cosmetic but kept ME-faithful.
const ZONE_ALPHA = 0.14901960784314;
// Zone ids must be unique within the mission; ME assigns small integers. Start high
// enough to avoid colliding with anything an author might later add by hand.
const ZONE_ID_BASE = 100;

function zoneColor(side: Side): [number, number, number, number] {
  return side === 'blue' ? [0, 0, 1, ZONE_ALPHA] : [1, 0, 0, ZONE_ALPHA];
}

/** Keep zone names to a safe charset while preserving the leading type word so
 *  zones.lua's `^%s*(%a+)` type selector still resolves to the keysite type. */
function sanitizeLabel(label: string): string {
  const cleaned = label
    .trim()
    .replace(/[^A-Za-z0-9]+/g, '-') // collapse runs of unsafe chars to a dash
    .replace(/^-+|-+$/g, ''); // trim leading/trailing dashes
  return cleaned.length > 0 ? cleaned : 'site';
}

/**
 * Project each keysite to DCS coordinates and turn it into a circular trigger zone.
 * name = `${type}_${label}` — the bare type is the first %a+ run so the port classifies
 * it; colour encodes the side. x = DCS north, y = DCS east (matching zones.lua's mapping).
 */
export function keysitesToZones(keysites: Keysite[], terrain: Terrain): DcsZone[] {
  return keysites.map((ks, i): DcsZone => {
    const dcs = latLonToDcs(ks.latlon, terrain);
    if (!Number.isFinite(dcs.x) || !Number.isFinite(dcs.y)) {
      throw new Error(
        `miz: keysite "${ks.label}" projected to a non-finite DCS point ` +
          `(${dcs.x}, ${dcs.y}); check the keysite's lat/lon and the terrain projection`,
      );
    }
    return {
      zoneId: ZONE_ID_BASE + i,
      name: `${ks.type}_${sanitizeLabel(ks.label)}`,
      x: dcs.x,
      y: dcs.y,
      radius: ks.radiusM,
      color: zoneColor(ks.side),
      side: ks.side,
      type: ks.type,
    };
  });
}

/** One DcsZone → the Lua sub-table DCS writes under triggers.zones (type 0 = circle). */
function zoneToLua(z: DcsZone): LuaObject {
  return {
    radius: z.radius,
    zoneId: z.zoneId,
    color: [z.color[0], z.color[1], z.color[2], z.color[3]],
    properties: {},
    hidden: false,
    y: z.y,
    x: z.x,
    name: z.name,
    heading: 0,
    type: 0, // 0 = circle (2 would be a quad); NOT the keysite type.
  };
}

