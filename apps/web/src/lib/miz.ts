// ── miz.ts — generate a valid DCS World .miz (a ZIP) from balanced keysites ──────
//
// Output pipeline tail:  balanced Keysite[]  →  projected DcsZone[]  →  mission
// table  →  serialized Lua  →  zipped .miz.  The .miz is an EMPTY Caucasus (or other
// theatre) mission carrying author-placed trigger zones — one circle per keysite.
// The EECH campaign port (Scripts/ee-dcs/zones.lua) reads these zones at
// runtime: a zone's COLOUR sets the side (blue={0,0,1}/red={1,0,0}) and the first word
// of its NAME sets the keysite type (airbase/farp/factory/…).
//
// By default the generator also SHIPS THE CAMPAIGN LUA inside the .miz so the file is
// directly playable: the built bundle (dist/ee-dcs.lua, mirrored into
// src/generated by scripts/sync-campaign.mjs) is embedded as l10n/DEFAULT/<name> and
// wired to run at mission start via mission.initScriptFile → a mapResource ResKey — the
// exact mechanism the DCS Mission Editor's "DO SCRIPT FILE" mission-init writes. Pass
// { bakeCampaign: false } to emit a zones-only .miz the author scripts themselves.
//
// The mission-table shape, key set, and the exact trigger-zone layout mirror what the
// DCS Mission Editor writes (studied from a real extracted .miz template); DCS is
// tolerant of whitespace, so the serializer matches structure/quoting, not byte layout.

